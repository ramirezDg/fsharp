let traducirPalabra (español:string) =
    diccionaruo
    |> Map.tryFind español
    |> Option.defaultValue español

let traducirFrase (frase: string) =
    frase.ToLower().Split(" ")
    |> Seq.map traducirPalabra
    |> String.concat " "
    |> fun s -> if String.IsNullOrWhiteSpace(s) then s else s.[0..0].ToUpper() + s.[1..]
